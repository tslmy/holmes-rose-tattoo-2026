import argparse
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from remaster import imagegen  # noqa: E402
from remaster.config import load_config  # noqa: E402
from remaster.stages import redraw_bg  # noqa: E402

CONFIG = """
[image]
local_generation = false
[bakeoff]
seed = 7
backends = ["web", "zc"]
levels = ["L2", "ZC-70"]
[bakeoff.variants.ZC-70]
level = "L1"
backends = ["zc"]
controls = [["depth", 0.7], ["hed", 0.5]]
[golden]
scenes = [4]
[image.backends.web]
tool = "http"
url = "http://x/v1/images/generations"
model = "m"
api_key_file = "{tmp}/key"
levels = { L2 = { steps = 8 } }
[image.backends.zc]
tool = "mflux-generate-z-image-controlnet"
model = "org/zc"
base_model = "z-image-controlnet"
steps = 9
allow_local = true
levels = { L1 = { control_strength = 0.75 } }
[image.backends.other-local]
tool = "mflux-generate"
model = "org/other"
base_model = "x"
"""


def make_cfg(tmp: str):
    path = Path(tmp) / "remaster.toml"
    path.write_text(CONFIG.replace("{tmp}", tmp))
    (Path(tmp) / "key").write_text("k")
    return load_config(path)


class ControlNetTest(unittest.TestCase):
    def test_allow_local_overrides_local_generation_off(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg = make_cfg(tmp)
            with mock.patch.object(imagegen, "mflux_tool", return_value="/bin/true"), \
                    mock.patch.object(imagegen, "hf_cached", return_value=True):
                self.assertIsNone(imagegen.availability(cfg, "zc"))
                self.assertIn("local generation is off", imagegen.availability(cfg, "other-local"))

    def test_variant_backends_and_controls(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg = make_cfg(tmp)
            var = redraw_bg.variant(cfg, "ZC-70")
            self.assertEqual(var["backends"], ["zc"])
            self.assertEqual(var["controls"], [["depth", 0.7], ["hed", 0.5]])
            plain = redraw_bg.variant(cfg, "L2")
            self.assertIsNone(plain["backends"])
            self.assertIsNone(plain["controls"])
            bk = imagegen.backend(cfg, "zc")
            settings = redraw_bg.request_settings(cfg, bk, "ZC-70")
            self.assertEqual(settings["controls"], [["depth", 0.7], ["hed", 0.5]])
            self.assertEqual(settings["control_strength"], 0.75)  # base level settings kept
            self.assertNotIn("controls", redraw_bg.request_settings(cfg, imagegen.backend(cfg, "web"), "L2"))

    def test_plan_runs_a_variant_only_on_its_backends(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg = make_cfg(tmp)
            args = argparse.Namespace(scenes=None, all=False)
            with mock.patch.object(imagegen, "availability", return_value=None):
                keys = {(s.params["backend"], s.params["level"]) for s in redraw_bg.plan(cfg, args)}
            self.assertIn(("zc", "ZC-70"), keys)
            self.assertNotIn(("web", "ZC-70"), keys)
            self.assertIn(("web", "L2"), keys)
            self.assertIn(("zc", "L2"), keys)  # plain levels have no backend restriction

    def test_generate_passes_every_control(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg = make_cfg(tmp)
            src = Path(tmp) / "plate.png"
            Image.new("RGB", (96, 64), (90, 40, 20)).save(src)
            out = Path(tmp) / "o.png"
            seen = {}

            def fake_run(cmd, **kwargs):
                seen["cmd"] = cmd
                Image.new("RGB", (96, 64)).save(out)
                return subprocess.CompletedProcess(cmd, 0, "", "")

            with mock.patch.object(imagegen, "availability", return_value=None), \
                    mock.patch.object(imagegen, "mflux_tool", return_value="/bin/zc"), \
                    mock.patch.object(imagegen.subprocess, "run", side_effect=fake_run):
                rec = imagegen.generate(cfg, "zc", prompt="p", images=[src], size=(96, 64), seed=7, out=out,
                                        level="ZC-70", settings={"control_strength": 0.75,
                                                                 "controls": [["depth", 0.7], ["hed", 0.5]]})
            cmd = seen["cmd"]
            specs = [cmd[i + 1] for i, part in enumerate(cmd) if part == "--control"]
            self.assertEqual(specs, [f"depth:{src}:0.7", f"hed:{src}:0.5"])
            self.assertEqual(cmd[cmd.index("--width") + 1], "96")
            self.assertEqual(cmd[cmd.index("--height") + 1], "64")
            self.assertEqual(rec["output_size"], [96, 64])

    def test_single_control_still_works(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg = make_cfg(tmp)
            src = Path(tmp) / "plate.png"
            Image.new("RGB", (96, 64)).save(src)
            out = Path(tmp) / "o.png"
            seen = {}

            def fake_run(cmd, **kwargs):
                seen["cmd"] = cmd
                Image.new("RGB", (96, 64)).save(out)
                return subprocess.CompletedProcess(cmd, 0, "", "")

            with mock.patch.object(imagegen, "availability", return_value=None), \
                    mock.patch.object(imagegen, "mflux_tool", return_value="/bin/zc"), \
                    mock.patch.object(imagegen.subprocess, "run", side_effect=fake_run):
                imagegen.generate(cfg, "zc", prompt="p", images=[src], size=(96, 64), seed=7, out=out,
                                  level="L1", settings={"control_strength": 0.75})
            cmd = seen["cmd"]
            self.assertEqual([cmd[i + 1] for i, p in enumerate(cmd) if p == "--control"], [f"canny:{src}:0.75"])


if __name__ == "__main__":
    unittest.main()
