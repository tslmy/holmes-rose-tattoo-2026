"""Acceptance test for delegate task `ambience` (iteration 3): animated room objects re-based on the redraw.

Written by Opus; the implementation is delegated. Do not edit this file to make it pass.
Fixtures are non-square (room 60x40, frames 10x6, 8x12 ...) so row/column mix-ups fail.

Animated room objects (lights, steam, dials, shadows, fans) are drawn by the engine from 1996 frames that
mostly copy the background under them, so on a redrawn room they show as old-art rectangles. Each frame
is rebuilt at 2x: pixels equal to the original plate take the redraw; pixels that only change brightness
(a light glow, a shadow) take the redraw scaled by the same per-channel ratio; other pixels keep the old
art, upscaled. Objects that are mostly not background (a walker) are left to the engine.
"""

import json
import sys
import tempfile
import unittest
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from remaster.config import load_config  # noqa: E402
from remaster.stages import assemble, extract, prepare  # noqa: E402

W, H = 60, 40


def plate_1x() -> np.ndarray:
    """Greyish (near-neutral) gradient, values 60..200, so a 1.5x glow stays under 255 and differs by > 8."""
    ys, xs = np.mgrid[0:H, 0:W]
    v = 60 + (xs * 2 + ys) % 100
    return np.stack([v, v + 4, v - 4], axis=-1).astype(np.uint8)


def redraw_2x() -> np.ndarray:
    """A coloured 2x 'redraw', unrelated to the plate."""
    ys, xs = np.mgrid[0:2 * H, 0:2 * W]
    return np.stack([40 + xs, 30 + ys * 2, 90 + (xs + ys) % 60], axis=-1).astype(np.uint8)


def obj(index, name, image_index, x, y, scale=256, required=None, kind="active_bg_shape"):
    return {"index": index, "name": name, "sprite_type": kind, "image_index": image_index,
            "position": {"x": x, "y": y}, "flags": 0, "scale_val": scale, "required_flags": required or []}


class AmbienceTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        (root / "remaster.toml").write_text("[golden]\nscenes = [4]\n")
        self.cfg = load_config(root / "remaster.toml")
        self.plate = plate_1x()
        prep = prepare.out_root(self.cfg) / "scene_012"
        prep.mkdir(parents=True)
        Image.fromarray(self.plate).save(prep / "plate.png")
        self.sprites = extract.scene_dir(self.cfg, "room-sprites", 12)
        rooms = extract.scene_dir(self.cfg, "rooms", 12)
        rooms.mkdir(parents=True)
        p = self.plate.astype(int)

        # LAMP (room_001): 2 frames 10x6 at (5, 4). Frame 0 = plate with a 3x2 glow (x1.5) at frame (2..4, 1..2)
        # and one transparent pixel; frame 1 has offset_x=2 and copies the plate exactly at its own place.
        f0 = p[4:10, 5:15].copy()
        f0[1:3, 2:5] = np.clip(f0[1:3, 2:5] * 1.5, 0, 255)
        a0 = np.full((6, 10), 255)
        a0[5, 9] = 0
        f1 = p[4:10, 7:17].copy()
        self.write_room(1, [(f0, a0, 0, 0), (f1, np.full((6, 10), 255), 2, 0)])
        # WALKER (room_002): solid dark figure, nothing like the background: left to the engine.
        fig = np.full((12, 8, 3), 9)
        self.write_room(2, [(fig, np.full((12, 8), 255), 0, 0)] * 2)
        # FAN (room_003): 8x12 at (30, 10); left half copies the plate, right half is pure red blades.
        fan = p[10:22, 30:38].copy()
        fan[:, 4:] = (255, 0, 0)
        self.write_room(3, [(fan, np.full((12, 8), 255), 0, 0)] * 2)
        # SHARED (room_004, two objects), FLAGGED (room_006), OUT (room_007, off the edge),
        # STATIC (room_008, one frame: room_sprites' job, not this one).
        bgcopy = lambda x, y, w, h: (p[y:y + h, x:x + w].copy(), np.full((h, w), 255), 0, 0)
        self.write_room(4, [bgcopy(40, 2, 4, 4)] * 2)
        self.write_room(6, [bgcopy(2, 30, 5, 5)] * 2)
        self.write_room(7, [bgcopy(50, 30, 10, 10)] * 2)
        self.write_room(8, [bgcopy(20, 30, 5, 4)])
        # COVER (room_009): one static frame, only in another story state (required flag 7): not in the
        # plate, so room_sprites cannot cut it; re-based here. Left half copies the plate, right half red.
        cov = p[30:36, 30:40].copy()
        cov[:, 5:] = (255, 0, 0)
        self.write_room(9, [(cov, np.full((6, 10), 255), 0, 0)])
        objects = [obj(0, "LAMP", 1, 5, 4), obj(1, "WALKER", 2, 20, 20), obj(2, "FAN", 3, 30, 10),
                   obj(3, "BUSTL", 4, 40, 2), obj(4, "BUSTR", 4, 40, 2),
                   obj(6, "HIDDEN", 6, 2, 30, required=[5]), obj(7, "EDGE", 7, 55, 35),
                   obj(8, "CHAIR", 8, 20, 30), obj(9, "PERSON", 1, 5, 4, kind="person"),
                   obj(10, "COVER", 9, 30, 30, required=[7])]
        (rooms / "metadata.json").write_text(json.dumps({"objects": objects}))
        self.redraw = redraw_2x()
        self.out = root / "out"

    def write_room(self, image_index, frames):
        room = self.sprites / f"room_{image_index:03d}"
        room.mkdir(parents=True)
        meta = []
        for i, (rgb, alpha, ox, oy) in enumerate(frames):
            rgba = np.dstack([np.asarray(rgb, np.uint8), np.asarray(alpha, np.uint8)])
            Image.fromarray(rgba, "RGBA").save(room / f"frame_{i:03d}.png")
            meta.append({"index": i, "file": f"frame_{i:03d}.png", "width": rgba.shape[1], "height": rgba.shape[0],
                         "offset_x": ox, "offset_y": oy, "invalid_placeholder": False})
        (room / "metadata.json").write_text(json.dumps({"room_index": image_index, "frame_count": len(frames),
                                                        "frames": meta}))

    def tearDown(self):
        self.tmp.cleanup()

    def run_it(self):
        return assemble.ambience_sprites(self.cfg, 12, Image.fromarray(self.redraw), self.out)

    def frame(self, image_index, i):
        return np.asarray(Image.open(self.out / f"room_{image_index:03d}" / f"frame_{i:03d}@2x.png"))

    def test_only_background_like_animated_objects_are_written(self):
        written = self.run_it()
        # objects of other story states are re-based too (HIDDEN animated, COVER static)
        self.assertEqual(sorted(w["name"] for w in written), ["COVER", "FAN", "HIDDEN", "LAMP"])
        lamp = next(w for w in written if w["name"] == "LAMP")
        self.assertEqual((lamp["image_index"], lamp["frames"]), (1, 2))
        self.assertGreater(lamp["bg_fraction"], 0.8)
        self.assertFalse(lamp["other_state"])
        cover = next(w for w in written if w["name"] == "COVER")
        self.assertTrue(cover["other_state"])
        self.assertEqual(cover["frames"], 1)
        for index in (2, 4, 7, 8):
            self.assertFalse((self.out / f"room_{index:03d}").exists(), index)

    def test_other_state_object_keeps_its_own_art_and_takes_the_redraw_behind(self):
        self.run_it()
        f = self.frame(9, 0).astype(int)
        self.assertEqual(f.shape, (12, 20, 4))
        np.testing.assert_array_equal(f[:, :8, :3], self.redraw[60:72, 60:68])  # plate copy -> redraw
        mid = f[2:-2, 12:18, :3].reshape(-1, 3).mean(axis=0)
        np.testing.assert_allclose(mid, (255, 0, 0), atol=12)  # its own art stays

    def test_an_image_room_sprites_already_wrote_is_left_alone(self):
        (self.out / "room_009").mkdir(parents=True)
        written = self.run_it()
        self.assertNotIn("COVER", [w["name"] for w in written])
        self.assertEqual(list((self.out / "room_009").iterdir()), [])

    def test_background_pixels_take_the_redraw(self):
        self.run_it()
        f1 = self.frame(1, 1)
        self.assertEqual(f1.shape, (12, 20, 4))
        # frame 1 is drawn at position + offset = (7, 4): its 2x box in the redraw is rows 8..20, cols 14..34
        np.testing.assert_array_equal(f1[..., :3], self.redraw[8:20, 14:34])
        f0 = self.frame(1, 0)
        np.testing.assert_array_equal(f0[:2, :, :3], self.redraw[8:10, 10:30])   # untouched row 0
        self.assertEqual(f0[11, 19, 3], 0)                                      # transparent stays transparent
        self.assertEqual(f0[10, 16, 3], 255)

    def test_glow_scales_the_redraw(self):
        self.run_it()
        f0 = self.frame(1, 0).astype(int)
        p = self.plate.astype(int)
        for fy, fx in ((1, 2), (2, 4)):
            ref = p[4 + fy, 5 + fx]
            glow = np.clip(ref * 1.5, 0, 255)
            ratio = (glow + 1) / (ref + 1)
            for dy in (0, 1):
                for dx in (0, 1):
                    y, x = 2 * fy + dy, 2 * fx + dx
                    want = np.clip(self.redraw[8 + y, 10 + x].astype(int) * ratio, 0, 255)
                    self.assertTrue(np.all(np.abs(f0[y, x, :3] - want) <= 3), (y, x, f0[y, x], want))

    def test_other_changes_keep_the_old_art(self):
        self.run_it()
        fan = self.frame(3, 0).astype(int)
        self.assertEqual(fan.shape, (24, 16, 4))
        np.testing.assert_array_equal(fan[:, :6, :3], self.redraw[20:44, 60:66])  # left (background) half
        blades = fan[2:22, 10:16, :3]  # well inside the red half, away from LANCZOS edge ringing
        self.assertTrue(np.all(blades[..., 0] >= 240) and np.all(blades[..., 1:] <= 15))

    def test_no_room_metadata_means_no_overrides(self):
        self.assertEqual(assemble.ambience_sprites(self.cfg, 99, Image.fromarray(self.redraw), self.out), [])

    def test_run_job_records_ambience(self):
        source = Path(assemble.__file__).read_text()
        body = source.split("def run_job")[1]
        self.assertIn("ambience_sprites(", body)
        self.assertIn('"ambience_sprites"', body)


if __name__ == "__main__":
    unittest.main()
