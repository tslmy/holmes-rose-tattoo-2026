"""Acceptance test for delegate task `maptiles` (iteration 8): tiling and seam blending for the map redraw.

Written by Opus; the implementation is delegated. Do not edit this file to make it pass.
Fixtures are non-square so row/column mix-ups fail.

The London map (MAP.VGS) is 1280x960 at 1x, far larger than the ~1 MP the image model redraws well, so it
is redrawn in overlapping tiles and blended back. tools/remaster/maptiles.py provides:

  tile_boxes(width, height, cols, rows, overlap) -> list[(x0, y0, x1, y1)]
      cols x rows tiles in row-major order (top row left to right first). Tile edges sit on an even grid
      (core edges at round(i * width / cols) and round(j * height / rows)); each tile extends its core by
      `overlap` px on every side that is not an image border, clamped to the image.

  blend_tiles(tiles, boxes, size) -> np.ndarray (height, width, 3) uint8
      tiles: list of HxWx3 arrays (uint8 or float), tile i the size of boxes[i] (x1-x0 wide, y1-y0 tall).
      size: (width, height). Weighted average of all tiles covering each pixel. A tile's weight is the
      product of a horizontal and a vertical ramp: 1 everywhere except inside the band of width
      2 * overlap around an interior edge, where it ramps linearly towards 0 at the tile's own border
      (overlap is recovered from the boxes, so the function needs no extra argument). Edges on the image
      border are not ramped. Every pixel must have positive total weight.
"""

import sys
import unittest
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from remaster import maptiles  # noqa: E402

W, H = 200, 120


def picture() -> np.ndarray:
    ys, xs = np.mgrid[0:H, 0:W]
    return np.stack([xs % 251, (ys * 2) % 241, (xs + 3 * ys) % 239], axis=-1).astype(np.uint8)


class TileBoxesTest(unittest.TestCase):
    def test_grid_covers_the_image_with_overlap(self):
        boxes = maptiles.tile_boxes(W, H, 4, 3, 10)
        self.assertEqual(len(boxes), 12)
        cover = np.zeros((H, W), int)
        for x0, y0, x1, y1 in boxes:
            self.assertTrue(0 <= x0 < x1 <= W and 0 <= y0 < y1 <= H)
            cover[y0:y1, x0:x1] += 1
        self.assertTrue((cover >= 1).all())
        # row-major: the second box is right of the first, the fifth starts the second row
        self.assertEqual(boxes[0][:2], (0, 0))
        self.assertGreater(boxes[1][0], boxes[0][0])
        self.assertEqual(boxes[4][0], 0)
        self.assertGreater(boxes[4][1], 0)
        # core edges at 50, 100, 150 (x) and 40, 80 (y); interior sides extended by 10
        self.assertEqual(boxes[0], (0, 0, 60, 50))
        self.assertEqual(boxes[1], (40, 0, 110, 50))
        self.assertEqual(boxes[3], (140, 0, 200, 50))
        self.assertEqual(boxes[5], (40, 30, 110, 90))
        self.assertEqual(boxes[11], (140, 70, 200, 120))

    def test_single_tile_is_the_whole_image(self):
        self.assertEqual(maptiles.tile_boxes(W, H, 1, 1, 16), [(0, 0, W, H)])


class BlendTest(unittest.TestCase):
    def test_crops_of_one_picture_blend_back_to_it(self):
        pic = picture()
        boxes = maptiles.tile_boxes(W, H, 3, 2, 12)
        tiles = [pic[y0:y1, x0:x1] for x0, y0, x1, y1 in boxes]
        out = maptiles.blend_tiles(tiles, boxes, (W, H))
        self.assertEqual(out.shape, (H, W, 3))
        self.assertEqual(out.dtype, np.uint8)
        self.assertLessEqual(np.abs(out.astype(int) - pic.astype(int)).max(), 1)

    def test_seam_ramps_from_one_tile_to_the_next(self):
        boxes = maptiles.tile_boxes(W, H, 2, 1, 20)  # cores 0-100 and 100-200; overlap band 80..120
        self.assertEqual(boxes, [(0, 0, 120, H), (80, 0, 200, H)])
        dark = np.zeros((H, 120, 3), np.uint8)
        bright = np.full((H, 120, 3), 200, np.uint8)
        out = maptiles.blend_tiles([dark, bright], boxes, (W, H)).astype(int)
        row = out[H // 2, :, 0]
        self.assertTrue((row[:80] == 0).all())  # only the left tile
        self.assertTrue((row[120:] == 200).all())  # only the right tile
        band = row[80:120]
        self.assertTrue((np.diff(band) >= 0).all())  # monotonic ramp, no step
        self.assertLess(np.abs(np.diff(band)).max(), 20)
        self.assertTrue(abs(row[100] - 100) <= 10)  # half way at the core edge
        # columns are uniform: the vertical image borders are not ramped
        self.assertTrue((out[0, :, 0] == out[H - 1, :, 0]).all())

    def test_middle_tiles_ramp_over_their_own_overlap(self):
        # three columns and three rows: the middle tile's neighbours are on both sides (Opus, after review)
        boxes = maptiles.tile_boxes(W, H, 3, 3, 6)
        flat = [np.full((y1 - y0, x1 - x0, 3), 10 * (k + 1), np.uint8) for k, (x0, y0, x1, y1) in enumerate(boxes)]
        out = maptiles.blend_tiles(flat, boxes, (W, H)).astype(int)
        row = out[60, :, 0]  # middle row of tiles: values 40, 50, 60
        cx = round(W / 3)
        self.assertTrue((row[:cx - 6] == 40).all())
        self.assertTrue((row[cx + 6:2 * cx - 6] == 50).all())
        self.assertTrue((row[2 * cx + 6:] == 60).all())
        self.assertTrue((np.diff(row[cx - 6:cx + 6]) >= 0).all())

    def test_float_tiles_are_accepted(self):
        pic = picture().astype(np.float32)
        boxes = maptiles.tile_boxes(W, H, 2, 2, 8)
        out = maptiles.blend_tiles([pic[y0:y1, x0:x1] for x0, y0, x1, y1 in boxes], boxes, (W, H))
        self.assertLessEqual(np.abs(out.astype(int) - picture().astype(int)).max(), 1)


if __name__ == "__main__":
    unittest.main()
