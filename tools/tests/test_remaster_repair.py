"""Acceptance test for delegate task `repair` (iteration 6): repair a room's best near-miss redraw.

Written by Opus; the implementation is delegated. Do not edit this file to make it pass.
Fixtures are non-square (plate 96x64) so row/column mix-ups fail.

After eight seeds, 20 rooms still keep the 1996 baseline, but each one's best redraw fails only one or two
QA gates: something added on the walkable floor (obstacles: a dog on a rug, a chair at a desk), people added
(vlm), or one small hotspot object missing (objects: a cup, a mail slot). A variant with `repair = true`
does not redraw: it takes the room's best near-miss (status ok, not passing, at most two failing gates;
fewest failing gates, then highest score), removes what QA found blocking (its `blocking_objects` boxes,
plus people the redraw added) with one edit of that redraw pasted back only around those boxes, then puts
each missing object back: the input plate's pixels pasted at the object's box (mapped through the
geometry warp into redraw pixels), harmonised by a second edit, pasted back only around those boxes.
"""

import json
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from remaster import detect, imagegen  # noqa: E402
from remaster.config import load_config  # noqa: E402
from remaster.stages import brief, geometry, prepare, qa, redraw_bg  # noqa: E402
from remaster.warp import GridWarp  # noqa: E402

CONFIG = """
[bakeoff]
seed = 7
backends = ["web"]
levels = ["L2-a", "L2-b", "L2-repair"]
[bakeoff.variants]
L2-a = {{ level = "L2", seed = 5 }}
L2-b = {{ level = "L2", seed = 6 }}
L2-repair = {{ level = "L2", repair = true }}
[image.backends.web]
tool = "http"
url = "http://x/v1/images/generations"
model = "m"
api_key_file = "{tmp}/key"
"""

PW, PH = 96, 64                      # plate size (original px)
RAW, OTHER = (200, 30, 30), (30, 200, 30)
CLEAN, HARM = (20, 40, 220), (10, 220, 220)
YELLOW = (250, 250, 0)               # the cup in the plate


def summary(fails: list[str], score: float, blocking=(), missing=(), passed=False):
    gates = {g: (g not in fails) for g in ("warp", "objects", "order", "obstacles", "vlm", "floor")}
    return {"summary": {"status": "ok", "pass": passed, "gates": gates, "score": score,
                        "blocking_objects": [{"label": lb, "box": list(b), "score": 0.3} for lb, b in blocking],
                        "missing": list(missing)}}


class RepairTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        tmp = self.tmp.name
        (Path(tmp) / "remaster.toml").write_text(CONFIG.format(tmp=tmp))
        (Path(tmp) / "key").write_text("k")
        self.cfg = load_config(Path(tmp) / "remaster.toml")
        prep = prepare.out_root(self.cfg) / "scene_012"
        prep.mkdir(parents=True)
        plate = np.full((PH, PW, 3), 90, np.uint8)
        plate[40:46, 10:18] = YELLOW  # the cup: orig box (10, 40, 8, 6)
        Image.fromarray(plate).save(prep / "plate_dedither.png")
        (prep / "plate.json").write_text('{"layers": [], "skipped": [], "size": [96, 64]}')
        out = brief.out_dir(self.cfg, 12)
        out.mkdir(parents=True)
        (out / "visual_brief.txt").write_text("BRIEF")
        self.size = redraw_bg.size_for(self.cfg, 12)
        self.sx, self.sy = self.size[0] / PW, self.size[1] / PH
        w, h = self.size
        # the dog: a box in redraw (picture) pixels, lower right
        self.dog = (int(0.6 * w), int(0.55 * h), int(0.15 * w), int(0.2 * h))
        self.write_source("L2-a", RAW, summary(["obstacles", "objects"], 0.6, blocking=[("dog", self.dog)],
                                               missing=["Cup"]))
        self.write_source("L2-b", OTHER, summary(["obstacles", "objects", "vlm"], 0.9))
        self.calls = []

    def write_source(self, level, colour, qa_json):
        d = redraw_bg.job_dir(self.cfg, 12, "web", level)
        d.mkdir(parents=True)
        Image.new("RGB", self.size, colour).save(d / "redraw.png")
        (d / "record.json").write_text('{"status": "ok"}')
        q = qa.job_dir(self.cfg, 12, "web", level)
        q.mkdir(parents=True, exist_ok=True)
        (q / "qa.json").write_text(json.dumps(qa_json))
        g = geometry.job_dir(self.cfg, 12, "web", level)
        g.mkdir(parents=True, exist_ok=True)
        warp = GridWarp.identity(PW, PH, (self.sx, self.sy))
        (g / "geometry.json").write_text(json.dumps({
            "warp": warp.to_json(), "picture_size": list(self.size), "original_size": [PW, PH],
            "anchors": [{"id": 1, "label": "Cup", "detectable": True, "orig_det": [10, 40, 8, 6],
                         "box": [10, 40, 8, 6], "orig_score": 0.5},
                        {"id": 2, "label": "Clock", "detectable": True, "orig_det": [70, 5, 6, 8],
                         "box": [70, 5, 6, 8], "orig_score": 0.5}]}))

    def tearDown(self):
        self.tmp.cleanup()

    def fake_generate(self, cfg, backend, *, prompt, images, size, seed, out, **kwargs):
        self.calls.append({"prompt": prompt, "image": np.asarray(Image.open(images[0]).convert("RGB")),
                           "size": size})
        Image.new("RGB", size, CLEAN if "Remove" in prompt else HARM).save(out)
        return {"backend": backend, "seconds": 1.0, "output_size": list(size)}

    def run_repair(self):
        with mock.patch.object(imagegen, "generate", side_effect=self.fake_generate), \
                mock.patch.object(detect, "detect", return_value=[]):
            redraw_bg.run_job(self.cfg, {"scene": 12, "backend": "web", "level": "L2-repair", "seed": 7}, "fp")
        target = redraw_bg.job_dir(self.cfg, 12, "web", "L2-repair")
        return target, np.asarray(Image.open(target / "redraw.png").convert("RGB")).astype(int)

    def test_variant_and_source(self):
        self.assertTrue(redraw_bg.variant(self.cfg, "L2-repair")["repair"])
        self.assertFalse(redraw_bg.variant(self.cfg, "L2-a")["repair"])
        # fewest failing gates wins over a higher score
        self.assertEqual(redraw_bg.repair_source(self.cfg, 12, "web"), "L2-a")

    def test_no_source_when_a_redraw_passes_or_misses_by_too_much(self):
        q = qa.job_dir(self.cfg, 12, "web", "L2-b")
        (q / "qa.json").write_text(json.dumps(summary([], 0.5, passed=True)))
        self.assertIsNone(redraw_bg.repair_source(self.cfg, 12, "web"))
        (q / "qa.json").write_text(json.dumps(summary(["obstacles", "objects", "vlm"], 0.9)))
        q = qa.job_dir(self.cfg, 12, "web", "L2-a")
        (q / "qa.json").write_text(json.dumps(summary(["obstacles", "objects", "floor"], 0.6)))
        self.assertIsNone(redraw_bg.repair_source(self.cfg, 12, "web"))

    def test_repair_removes_blockers_and_restores_missing_objects(self):
        target, out = self.run_repair()
        self.assertEqual(len(self.calls), 2)
        removal, harmonise = self.calls
        self.assertIn("Remove", removal["prompt"])
        self.assertIn("dog", removal["prompt"])
        self.assertTrue(np.all(removal["image"] == RAW))  # edits the source redraw
        self.assertIn("Blend", harmonise["prompt"])
        self.assertIn("Cup", harmonise["prompt"])
        cx, cy = int((10 + 4) * self.sx), int((40 + 3) * self.sy)
        np.testing.assert_array_equal(harmonise["image"][cy, cx], YELLOW)  # the plate's cup, pasted first
        dx, dy = self.dog[0] + self.dog[2] // 2, self.dog[1] + self.dog[3] // 2
        np.testing.assert_array_equal(out[dy, dx], CLEAN)
        np.testing.assert_array_equal(out[cy, cx], HARM)
        np.testing.assert_array_equal(out[2, 2], RAW)  # elsewhere: the source redraw exactly
        clock = (int((70 + 3) * self.sx), int((5 + 4) * self.sy))
        np.testing.assert_array_equal(out[clock[1], clock[0]], RAW)  # not missing: untouched
        record = json.loads((target / "record.json").read_text())
        self.assertEqual(record["source"], "L2-a")
        self.assertEqual([r["label"] for r in record["removed"]], ["dog"])
        self.assertEqual([r["label"] for r in record["restored"]], ["Cup"])
        self.assertEqual(record["status"], "ok")

    def test_only_anchors_qa_did_not_find_are_restored(self):
        # two anchors share the label; QA's rows say only the second (id 3) was not found
        g = geometry.job_dir(self.cfg, 12, "web", "L2-a") / "geometry.json"
        doc = json.loads(g.read_text())
        doc["anchors"].append({"id": 3, "label": "Cup", "detectable": True, "orig_det": [60, 40, 8, 6],
                               "box": [60, 40, 8, 6], "orig_score": 0.5})
        g.write_text(json.dumps(doc))
        q = qa.job_dir(self.cfg, 12, "web", "L2-a") / "qa.json"
        doc = json.loads(q.read_text())
        doc["objects"] = {"objects": [{"id": 1, "label": "Cup", "found": True},
                                      {"id": 3, "label": "Cup", "found": False}]}
        q.write_text(json.dumps(doc))
        target, out = self.run_repair()
        record = json.loads((target / "record.json").read_text())
        self.assertEqual(len(record["restored"]), 1)
        cx, cy = int((10 + 4) * self.sx), int((40 + 3) * self.sy)
        np.testing.assert_array_equal(out[cy, cx], RAW)       # the found cup: untouched
        cx3 = int((60 + 4) * self.sx)
        np.testing.assert_array_equal(out[cy, cx3], HARM)     # the unfound one: restored

    def test_object_detected_off_position_is_not_restored(self):
        # QA counts the cup as missing, but the detector saw it in the redraw (displaced): pasting the plate's
        # cup would make a second one
        g = geometry.job_dir(self.cfg, 12, "web", "L2-a") / "geometry.json"
        doc = json.loads(g.read_text())
        doc["anchors"][0]["redraw_det"] = [5 * self.sx, 30 * self.sy, 8 * self.sx, 6 * self.sy]
        g.write_text(json.dumps(doc))
        target, out = self.run_repair()
        record = json.loads((target / "record.json").read_text())
        self.assertEqual(record["restored"], [])
        self.assertEqual(len(self.calls), 1)  # the removal edit only
        cx, cy = int((10 + 4) * self.sx), int((40 + 3) * self.sy)
        np.testing.assert_array_equal(out[cy, cx], RAW)

    def test_no_source_means_unavailable(self):
        q = qa.job_dir(self.cfg, 12, "web", "L2-a")
        (q / "qa.json").write_text(json.dumps(summary([], 0.6, passed=True)))
        target, _ = (None, None)
        with mock.patch.object(imagegen, "generate", side_effect=self.fake_generate), \
                mock.patch.object(detect, "detect", return_value=[]):
            redraw_bg.run_job(self.cfg, {"scene": 12, "backend": "web", "level": "L2-repair", "seed": 7}, "fp")
        record = json.loads((redraw_bg.job_dir(self.cfg, 12, "web", "L2-repair") / "record.json").read_text())
        self.assertEqual(record["status"], "unavailable")
        self.assertEqual(self.calls, [])

    def test_plan_fingerprint_follows_the_source_qa(self):
        import argparse
        args = argparse.Namespace(scenes=[12], all=False)
        with mock.patch.object(imagegen, "availability", return_value=None):
            fp1 = {s.key: s.fingerprint for s in redraw_bg.plan(self.cfg, args)}
            q = qa.job_dir(self.cfg, 12, "web", "L2-a")
            (q / "qa.json").write_text(json.dumps(summary(["objects"], 0.7, missing=["Cup"])))
            fp2 = {s.key: s.fingerprint for s in redraw_bg.plan(self.cfg, args)}
        k = redraw_bg.key(12, "web", "L2-repair")
        self.assertNotEqual(fp1[k], fp2[k])
        self.assertEqual(fp1[redraw_bg.key(12, "web", "L2-b")], fp2[redraw_bg.key(12, "web", "L2-b")])


if __name__ == "__main__":
    unittest.main()
