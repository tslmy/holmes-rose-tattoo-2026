import base64
import io
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from remaster import bakeoff, imagegen  # noqa: E402
from remaster.config import load_config  # noqa: E402
from remaster.stages import brief, redraw_bg  # noqa: E402

CONFIG = """
[bakeoff]
seed = 7
levels = ["L2", "L2-fix", "L1-s85", "L2-mask"]
[bakeoff.variants.L2-fix]
level = "L2"
extras = ["keep_figures", "no_new_light", "framing"]
seed = 11
[bakeoff.variants.L1-s85]
level = "L1"
strength = 0.85
[bakeoff.variants.L2-mask]
level = "L2"
extras = ["keep_figures"]
mask_people = true
[image.backends.web]
tool = "http"
url = "http://x/v1/images/generations"
model = "m"
api_key_file = "{tmp}/key"
levels = {{ L1 = {{ strength = 0.45, steps = 8 }}, L2 = {{ steps = 8 }} }}
"""


def make_cfg(tmp: str):
    path = Path(tmp) / "remaster.toml"
    path.write_text(CONFIG.replace("{tmp}", tmp).replace("{{", "{").replace("}}", "}"))
    (Path(tmp) / "key").write_text("k")
    return load_config(path)


class VariantTest(unittest.TestCase):
    def test_base_level_and_variant_fields(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg = make_cfg(tmp)
            self.assertEqual(redraw_bg.base_level(cfg, "L2"), "L2")
            self.assertEqual(redraw_bg.base_level(cfg, "L2-fix"), "L2")
            self.assertEqual(redraw_bg.base_level(cfg, "L1-s85"), "L1")
            plain = redraw_bg.variant(cfg, "L2")
            self.assertEqual({k: plain[k] for k in ("name", "level", "seed", "strength", "extras", "mask_people")},
                             {"name": "L2", "level": "L2", "seed": 7, "strength": None, "extras": [],
                              "mask_people": False})
            fix = redraw_bg.variant(cfg, "L2-fix")
            self.assertEqual((fix["level"], fix["seed"]), ("L2", 11))
            self.assertEqual(fix["extras"], ["keep_figures", "no_new_light", "framing"])
            self.assertTrue(redraw_bg.variant(cfg, "L2-mask")["mask_people"])
            with self.assertRaises(KeyError):
                redraw_bg.variant(cfg, "L9-nope")

    def test_prompt_has_level_text_then_extras(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg = make_cfg(tmp)
            out = brief.out_dir(cfg, 4)
            out.mkdir(parents=True)
            (out / "visual_brief.txt").write_text("BRIEF TEXT")
            for key in ("keep_figures", "no_new_light", "framing"):
                self.assertIn(key, imagegen.PROMPT_EXTRAS)
            text = redraw_bg.prompt_for(cfg, 4, "L2-fix")
            parts = [imagegen.level_prompt("L2")] + [imagegen.PROMPT_EXTRAS[k]
                                                     for k in ("keep_figures", "no_new_light", "framing")]
            self.assertTrue(text.startswith("BRIEF TEXT"))
            positions = [text.index(p) for p in parts]
            self.assertEqual(positions, sorted(positions))
            self.assertEqual(redraw_bg.prompt_for(cfg, 4, "L2"), "BRIEF TEXT\n\n" + imagegen.level_prompt("L2"))

    def test_style_no_longer_invites_fires(self):
        self.assertNotIn("fire", brief.STYLE.lower())

    def test_request_settings_override_strength(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg = make_cfg(tmp)
            bk = imagegen.backend(cfg, "web")
            self.assertEqual(redraw_bg.request_settings(cfg, bk, "L1-s85"), {"strength": 0.85, "steps": 8})
            self.assertEqual(redraw_bg.request_settings(cfg, bk, "L2-fix"), {"steps": 8})

    def test_generate_uses_explicit_settings(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg = make_cfg(tmp)
            Image.new("RGB", (8, 8)).save(Path(tmp) / "in.png")
            buf = io.BytesIO()
            Image.new("RGB", (8, 8)).save(buf, "PNG")
            reply = {"data": [{"b64_json": base64.b64encode(buf.getvalue()).decode()}]}
            with mock.patch.object(imagegen, "availability", return_value=None), \
                    mock.patch.object(imagegen, "post_json", return_value=reply) as post:
                rec = imagegen.generate(cfg, "web", prompt="p", images=[Path(tmp) / "in.png"], size=(8, 8),
                                        seed=11, out=Path(tmp) / "o.png", level="L1-s85",
                                        settings={"strength": 0.85, "steps": 8})
            payload = post.call_args.args[1]
            self.assertEqual((payload["strength"], payload["steps"], payload["seed"]), (0.85, 8, 11))
            self.assertEqual(rec["settings"], {"strength": 0.85, "steps": 8})

    def test_pick_ranks_variants_by_base_level(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg = make_cfg(tmp)
            (Path(tmp) / "remaster.toml").write_text(
                (Path(tmp) / "remaster.toml").read_text() + "\n[golden]\nscenes = [4]\n")
            cfg = load_config(Path(tmp) / "remaster.toml")

            def row(level, ok, score):
                return {"scene": 4, "backend": "web", "level": level, "status": "ok", "reason": None,
                        "seconds": 1.0, "peak_memory_gb": None, "pass": ok, "score": score, "qa": {},
                        "geometry": {}}
            rows = [row("L1-s85", True, 0.9), row("L2-fix", True, 0.7), row("L2", False, 0.95)]
            picks = bakeoff.pick(cfg, rows, bakeoff.aggregate(rows))
            self.assertEqual(picks["levels"][4]["level"], "L2-fix")

    def test_stages_compare_base_levels_not_names(self):
        root = Path(redraw_bg.__file__).parent
        for name in ("geometry.py", "qa.py"):
            source = (root / name).read_text()
            self.assertNotIn('level == "L', source, name)
            self.assertIn("base_level", source, name)


if __name__ == "__main__":
    unittest.main()
