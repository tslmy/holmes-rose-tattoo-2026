"""Acceptance test for delegate task `peopleclean` (iteration 3): remove people the redraw added.

Written by Opus; the implementation is delegated. Do not edit this file to make it pass.
Fixtures are non-square (generation size 96x64) so row/column mix-ups fail.

FLUX.2 Klein adds people to empty rooms however the prompt is worded (iteration 2: 347 of 320+ candidate
reviews). A variant with `remove_people = true` detects people in the redraw that have no counterpart in
the input, asks the same backend to remove them from the redraw, and pastes the cleaned pixels back only
inside those (grown, feathered) boxes, so the rest of the redraw is untouched.
"""

import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from remaster import detect, imagegen  # noqa: E402
from remaster.config import load_config  # noqa: E402
from remaster.stages import brief, prepare, redraw_bg  # noqa: E402

CONFIG = """
[bakeoff]
seed = 7
backends = ["web"]
levels = ["L2-clean", "L2-plain"]
[bakeoff.variants]
L2-clean = {{ level = "L2", seed = 5, remove_people = true }}
L2-plain = {{ level = "L2", seed = 5 }}
[image.backends.web]
tool = "http"
url = "http://x/v1/images/generations"
model = "m"
api_key_file = "{tmp}/key"
"""

RAW, CLEAN = (200, 30, 30), (20, 40, 220)


class PeopleCleanTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        tmp = self.tmp.name
        (Path(tmp) / "remaster.toml").write_text(CONFIG.format(tmp=tmp))
        (Path(tmp) / "key").write_text("k")
        self.cfg = load_config(Path(tmp) / "remaster.toml")
        prep = prepare.out_root(self.cfg) / "scene_012"
        prep.mkdir(parents=True)
        Image.new("RGB", (96, 64), (90, 90, 90)).save(prep / "plate_dedither.png")
        (prep / "plate.json").write_text('{"layers": [], "skipped": [], "size": [96, 64]}')
        out = brief.out_dir(self.cfg, 12)
        out.mkdir(parents=True)
        (out / "visual_brief.txt").write_text("BRIEF")
        self.size = redraw_bg.size_for(self.cfg, 12)
        self.calls = []
        self.raw_calls = 1  # how many generations return the raw (person-bearing) colour

    def tearDown(self):
        self.tmp.cleanup()

    def fake_generate(self, cfg, backend, *, prompt, images, size, seed, out, **kwargs):
        first = len(self.calls) < self.raw_calls
        self.calls.append({"prompt": prompt, "image": np.asarray(Image.open(images[0]).convert("RGB")),
                           "seed": seed, "settings": kwargs.get("settings")})
        Image.new("RGB", size, RAW if first else CLEAN).save(out)
        return {"backend": backend, "seconds": 1.0, "output_size": list(size)}

    def run_job(self, level, redraw_people, input_people=()):
        w, h = self.size

        def fake_detect(image, queries, threshold=0.05):
            img = image.convert("RGB")
            if img.getpixel((w // 2, h // 2)) == (90, 90, 90):
                boxes = input_people
            else:  # a person is "seen" while the pixel at its box centre is still the raw redraw
                boxes = [(b, sc) for b, sc in redraw_people
                         if img.getpixel((int(b[0] + b[2] / 2), int(b[1] + b[3] / 2))) == RAW]
            return [{"query": 0, "score": score, "box": list(box)} for box, score in boxes]

        with mock.patch.object(imagegen, "generate", side_effect=self.fake_generate), \
                mock.patch.object(detect, "detect", side_effect=fake_detect):
            redraw_bg.run_job(self.cfg, {"scene": 12, "backend": "web", "level": level, "seed": 5}, "fp")
        target = redraw_bg.job_dir(self.cfg, 12, "web", level)
        return target, np.asarray(Image.open(target / "redraw.png").convert("RGB")).astype(int)

    def test_added_person_is_painted_out_inside_its_box_only(self):
        box = (60, 10, 14, 30)  # x, y, w, h in generation pixels
        target, out = self.run_job("L2-clean", [(box, 0.6)])
        self.assertEqual(len(self.calls), 2)
        second = self.calls[1]
        self.assertTrue(np.all(second["image"] == RAW))     # the cleanup edits the redraw, not the plate
        self.assertIn("Remove every person", second["prompt"])
        self.assertEqual(second["seed"], 5)
        np.testing.assert_array_equal(out[25, 67], CLEAN)   # box centre: cleaned
        np.testing.assert_array_equal(out[5, 5], RAW)       # far away: the first redraw, exactly
        np.testing.assert_array_equal(out[55, 30], RAW)
        self.assertTrue((target / "redraw_raw.png").is_file())
        import json
        record = json.loads((target / "record.json").read_text())
        self.assertEqual(record["people_removed"], 1)
        self.assertIn("cleanup", record)

    def test_second_pass_when_the_first_cleanup_leaves_the_person(self):
        self.raw_calls = 2
        target, out = self.run_job("L2-clean", [((60, 10, 14, 30), 0.6)])
        self.assertEqual(len(self.calls), 3)
        self.assertEqual(self.calls[2]["seed"], 6)
        np.testing.assert_array_equal(out[25, 67], CLEAN)
        import json
        record = json.loads((target / "record.json").read_text())
        self.assertEqual((record["people_removed"], record["people_left"], len(record["cleanup"])), (2, 0, 2))

    def test_person_already_in_the_input_is_kept(self):
        box = (20, 12, 12, 30)
        _, out = self.run_job("L2-clean", [(box, 0.7)], input_people=[((22, 14, 11, 28), 0.5)])
        self.assertEqual(len(self.calls), 1)
        np.testing.assert_array_equal(out[27, 26], RAW)

    def test_overlapping_input_person_is_kept_by_iou(self):
        # the input box misses the redraw box's centre but overlaps it heavily (IoU > 0.3)
        _, out = self.run_job("L2-clean", [((20, 12, 12, 30), 0.7)], input_people=[((20, 0, 12, 26), 0.5)])
        self.assertEqual(len(self.calls), 1)
        np.testing.assert_array_equal(out[27, 26], RAW)

    def test_weak_detections_are_ignored(self):
        target, _ = self.run_job("L2-clean", [((60, 10, 14, 30), 0.1)])
        self.assertEqual(len(self.calls), 1)
        self.assertFalse((target / "redraw_raw.png").exists())

    def test_plain_variant_never_cleans(self):
        _, out = self.run_job("L2-plain", [((60, 10, 14, 30), 0.9)])
        self.assertEqual(len(self.calls), 1)
        np.testing.assert_array_equal(out[25, 67], RAW)

    def test_variant_reads_the_flag(self):
        self.assertTrue(redraw_bg.variant(self.cfg, "L2-clean")["remove_people"])
        self.assertFalse(redraw_bg.variant(self.cfg, "L2-plain")["remove_people"])


if __name__ == "__main__":
    unittest.main()
