"""Acceptance test for delegate task `firegate` (Phase 1c): new light is allowed, story fire fails.

Written by Opus; the implementation is delegated. Do not edit this file to make it pass.
"""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from remaster.stages import qa  # noqa: E402


class FireGateTest(unittest.TestCase):
    def test_vlm_diff_asks_for_story_fire(self):
        self.assertIn('"story_fire"', qa.VLM_DIFF)
        self.assertIn("fireplace", qa.VLM_DIFF.split('"story_fire"')[1])
        self.assertIn('"new_light_sources"', qa.VLM_DIFF)  # still recorded

    def test_fire_gate(self):
        self.assertIsNone(qa.fire_gate(None))
        self.assertTrue(qa.fire_gate({"new_light_sources": ["fire in the fireplace", "table lamp"]}))
        self.assertTrue(qa.fire_gate({"story_fire": []}))
        self.assertFalse(qa.fire_gate({"story_fire": ["flames coming out of the upper windows"]}))
        self.assertTrue(qa.fire_gate({"story_fire": ["", None]}))  # blank entries do not count

    def test_light_is_not_a_gate_any_more(self):
        source = Path(qa.__file__).read_text()
        self.assertNotIn('gates["light"]', source)
        self.assertIn('gates["fire"]', source)
        self.assertIn("fire_gate(", source.split("def evaluate")[1])
        # new light sources are still written to the summary
        self.assertIn('"new_light_sources":', source.split("def evaluate")[1])


if __name__ == "__main__":
    unittest.main()
