"""Acceptance test for delegate task `canims` (iteration 5): story animations on the room's own background.

Written by Opus; the implementation is delegated. Do not edit this file to make it pass.
Fixtures are non-square (room 60x40) so row/column mix-ups fail.

Cutscene animations (cAnims: Holmes picking something up, a door opening) are streamed per room and drawn at
position + frame offset; their frames copy much of the 1996 room behind them. The playable pack has no
override for them, so on a redrawn room they flash old-art rectangles. The engine loads an override from
<pack>/sprites/scene_NNN/canim_NNN/frame_iii@2x.png (zero-based cAnim and frame numbers) and mirrors it when
the cAnim's flags & 4, so overrides are stored unmirrored, like the extracted frames.
"""

import json
import sys
import tempfile
import unittest
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from remaster.config import load_config  # noqa: E402
from remaster.stages import assemble, extract, prepare  # noqa: E402

W, H = 60, 40
MAGENTA = (255, 0, 255)


def plate_1x() -> np.ndarray:
    ys, xs = np.mgrid[0:H, 0:W]
    v = 60 + (xs * 2 + ys) % 100
    return np.stack([v, v + 4, v - 4], axis=-1).astype(np.uint8)


def redraw_2x() -> np.ndarray:
    ys, xs = np.mgrid[0:2 * H, 0:2 * W]
    return np.stack([40 + xs, 30 + ys, 90 + (xs + ys) % 60], axis=-1).astype(np.uint8)


class CanimTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        (root / "remaster.toml").write_text('[golden]\nscenes = [4]\n[assemble]\ncanim_upscaled = "up"\n')
        self.cfg = load_config(root / "remaster.toml")
        self.plate = plate_1x()
        prep = prepare.out_root(self.cfg) / "scene_012"
        prep.mkdir(parents=True)
        Image.fromarray(self.plate).save(prep / "plate.png")
        self.canims = extract.scene_dir(self.cfg, "canimations", 12)
        self.up = root / "up" / "scene_012"
        p = self.plate.astype(int)

        # GRAB (canim_000) at (10, 8), unflipped, 8x6 frames. Frame 0 copies the plate with a 2x2 figure at
        # rows 1-2, cols 2-3 and a transparent pixel at (0, 0); frame 1, offset (3, 2), copies the plate;
        # frame 2 is an invalid placeholder. An upscaled frame 0 exists (solid blue): figure pixels take it.
        g0 = p[8:14, 10:18].copy()
        g0[1:3, 2:4] = MAGENTA
        a0 = np.full((6, 8), 255, np.uint8)
        a0[0, 0] = 0
        g1 = p[10:16, 13:21].copy()
        self.write_canim(0, "GRAB", (10, 8), 0, [(g0, a0, 0, 0), (g1, None, 3, 2), None])
        (self.up / "canim_000").mkdir(parents=True)
        Image.new("RGBA", (16, 12), (0, 0, 250, 255)).save(self.up / "canim_000" / "frame_000@2x.png")
        # a wrong-size upscaled frame 1 is ignored (frame 1 has no figure anyway)
        Image.new("RGBA", (5, 5), (0, 250, 0, 255)).save(self.up / "canim_000" / "frame_001@2x.png")

        # FLIP (canim_001) at (30, 10), flags 4: drawn mirrored. The stored frame is the plate under it
        # mirrored, with its stored column 0 (the rightmost on screen) magenta.
        f0 = p[10:16, 30:40][:, ::-1].copy()
        f0[:, 0] = MAGENTA
        self.write_canim(1, "FLIP", (30, 10), 4, [(f0, None, 0, 0)])

        # EDGE (canim_002) at (55, 30), 10x6: the drawn box leaves the plate on the right. Columns 0-4 copy
        # the plate; columns 5-9 (off the plate) are yellow.
        e0 = np.zeros((6, 10, 3), int)
        e0[:, :5] = p[30:36, 55:60]
        e0[:, 5:] = (200, 200, 0)
        self.write_canim(2, "EDGE", (55, 30), 0, [(e0, None, 0, 0)])

        # ACTOR (canim_003) at (2, 2): all figure, no background at all. Still written (old art, upscaled).
        self.write_canim(3, "ACTOR", (2, 2), 0, [(np.full((4, 6, 3), MAGENTA), None, 0, 0)])

        # SPECK (canim_004) at (40, 2): a 6x6 figure whose pixel (2, 2) happens to equal the plate under it,
        # and a DIM (canim_005) at (20, 30): a 6x4 frame that is the plate at 60% brightness (a figure in
        # shadow, or a door swinging). cAnims keep neither as background: isolated matches inside a figure
        # (narrower than 3 px) and brightness-only changes stay old art.
        k = np.full((6, 6, 3), MAGENTA, int)
        k[2, 2] = p[4, 42]
        self.write_canim(4, "SPECK", (40, 2), 0, [(k, None, 0, 0)])
        self.write_canim(5, "DIM", (20, 30), 0, [((p[30:34, 20:26] * 0.6).astype(int), None, 0, 0)])
        self.redraw = redraw_2x()
        self.out = root / "out"

    def write_canim(self, index, name, pos, flags, frames):
        d = self.canims / f"canim_{index:03d}"
        d.mkdir(parents=True)
        meta = []
        for i, item in enumerate(frames):
            if item is None:
                meta.append({"index": i, "file": f"frame_{i:03d}.png", "width": 0, "height": 0,
                             "offset_x": 0, "offset_y": 0, "invalid_placeholder": True})
                continue
            rgb, alpha, ox, oy = item
            rgb = np.asarray(np.clip(rgb, 0, 255), np.uint8)
            if alpha is None:
                alpha = np.full(rgb.shape[:2], 255, np.uint8)
            Image.fromarray(np.dstack([rgb, alpha]), "RGBA").save(d / f"frame_{i:03d}.png")
            meta.append({"index": i, "file": f"frame_{i:03d}.png", "width": rgb.shape[1], "height": rgb.shape[0],
                         "offset_x": ox, "offset_y": oy})
        (d / "metadata.json").write_text(json.dumps({
            "resource_name": f"scene_012/canim_{index:03d}", "scene_id": 12, "canim_index": index,
            "animation": {"index": index, "name": name, "position": {"x": pos[0], "y": pos[1]}, "flags": flags,
                          "scale_val": 256},
            "frame_count": len(frames), "frames": meta}))

    def tearDown(self):
        self.tmp.cleanup()

    def run_it(self):
        return assemble.canim_sprites(self.cfg, 12, Image.fromarray(self.redraw), self.out)

    def frame(self, canim, i):
        return np.asarray(Image.open(self.out / f"canim_{canim:03d}" / f"frame_{i:03d}@2x.png")).astype(int)

    def test_records(self):
        written = {w["name"]: w for w in self.run_it()}
        self.assertEqual(sorted(written), ["ACTOR", "DIM", "EDGE", "FLIP", "GRAB", "SPECK"])
        self.assertEqual(written["GRAB"]["canim"], 0)
        self.assertEqual(written["GRAB"]["frames"], 2)
        self.assertTrue(written["FLIP"]["flipped"])
        self.assertFalse(written["GRAB"]["flipped"])
        self.assertEqual(written["GRAB"]["scale"], 256)
        self.assertEqual(written["ACTOR"]["bg_fraction"], 0.0)
        self.assertGreater(written["GRAB"]["bg_fraction"], 0.9)
        self.assertFalse((self.out / "canim_000" / "frame_002@2x.png").exists())  # invalid placeholder

    def test_background_takes_the_redraw_and_figure_the_upscaled_frame(self):
        self.run_it()
        f0 = self.frame(0, 0)
        self.assertEqual(f0.shape, (12, 16, 4))
        r = self.redraw[16:28, 20:36].astype(int)
        figure = np.zeros((12, 16), bool)
        figure[2:6, 4:8] = True
        opaque = f0[..., 3] > 0
        np.testing.assert_array_equal(f0[~figure & opaque, :3], r[~figure & opaque])
        np.testing.assert_array_equal(f0[figure, :3], np.tile([0, 0, 250], (16, 1)))
        np.testing.assert_array_equal(f0[0:2, 0:2, 3], 0)  # alpha upscaled NEAREST
        self.assertTrue((f0[2:, :, 3] == 255).all())
        # frame 1 at offset (3, 2): the redraw under its own box; the wrong-size upscaled file is not used
        f1 = self.frame(0, 1)
        np.testing.assert_array_equal(f1[..., :3], self.redraw[20:32, 26:42])

    def test_flipped_canim_is_stored_unmirrored(self):
        self.run_it()
        f = self.frame(1, 0)
        r = self.redraw[20:32, 60:80][:, ::-1].astype(int)
        np.testing.assert_array_equal(f[:, 2:, :3], r[:, 2:])
        # the magenta column keeps old art (LANCZOS-upscaled, no upscaled file): still clearly magenta
        col = f[1:-1, 0, :3].mean(axis=0)
        self.assertGreater(col[0], 180)
        self.assertLess(col[1], 80)

    def test_pixels_off_the_plate_keep_old_art(self):
        self.run_it()
        f = self.frame(2, 0)
        self.assertEqual(f.shape, (12, 20, 4))
        np.testing.assert_array_equal(f[:, :10, :3], self.redraw[60:72, 110:120])
        mid = f[2:-2, 12:18, :3].reshape(-1, 3).mean(axis=0)
        np.testing.assert_allclose(mid, (200, 200, 0), atol=12)

    def test_figure_only_canim_is_old_art(self):
        self.run_it()
        f = self.frame(3, 0)
        self.assertEqual(f.shape, (8, 12, 4))
        np.testing.assert_allclose(f[2:-2, 2:-2, :3].reshape(-1, 3).mean(axis=0), MAGENTA, atol=12)

    def test_isolated_matches_and_brightness_changes_stay_old_art(self):
        written = {w["name"]: w for w in self.run_it()}
        speck = self.frame(4, 0)
        k = np.full((6, 6, 3), MAGENTA, np.uint8)
        k[2, 2] = self.plate[4, 42]
        old_k = np.asarray(Image.fromarray(k).resize((12, 12), Image.LANCZOS)).astype(int)
        np.testing.assert_array_equal(speck[..., :3], old_k)  # the whole frame is old art, the match too
        self.assertEqual(written["SPECK"]["bg_fraction"], 0.0)
        dim = self.frame(5, 0)
        old = np.asarray(Image.fromarray((self.plate[30:34, 20:26] * 0.6).astype(np.uint8))
                         .resize((12, 8), Image.LANCZOS)).astype(int)
        np.testing.assert_array_equal(dim[..., :3], old)
        self.assertEqual(written["DIM"]["bg_fraction"], 0.0)

    def test_room_without_canims(self):
        self.assertEqual(assemble.canim_sprites(self.cfg, 13, Image.fromarray(self.redraw), self.out), [])


if __name__ == "__main__":
    unittest.main()
