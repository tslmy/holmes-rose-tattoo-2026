"""Acceptance test for delegate task `staticplate` (iteration 2): plates without animated objects.

Written by Opus; the implementation is delegated. Do not edit this file to make it pass.
Fixture frames are non-square so width/height mix-ups fail.

Animated room objects (people, walkers, fire: their room image has more than one frame) are drawn by the
engine over the background. Baking them into the plate that is redrawn makes them appear twice in game.
With [prepare] plate_layers = "static" the plate keeps only single-frame objects.
"""

import json
import sys
import tempfile
import unittest
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from remaster import plates  # noqa: E402
from remaster.config import load_config  # noqa: E402
from remaster.stages import prepare  # noqa: E402


def make_room(root: Path, image_index: int, frames: list[tuple[int, int]]) -> None:
    room = root / f"room_{image_index:03d}"
    room.mkdir(parents=True)
    meta = []
    for i, (w, h) in enumerate(frames):
        Image.new("RGBA", (w, h), (200, 50, 50, 255)).save(room / f"frame_{i:03d}.png")
        meta.append({"index": i, "file": f"frame_{i:03d}.png", "width": w, "height": h,
                     "offset_x": 0, "offset_y": 0, "invalid_placeholder": False})
    (room / "metadata.json").write_text(json.dumps({"room_index": image_index, "frame_count": len(frames),
                                                    "frames": meta}))


def obj(index: int, name: str, image_index: int, x: int, y: int) -> dict:
    return {"index": index, "name": name, "sprite_type": "active_bg_shape", "image_index": image_index,
            "position": {"x": x, "y": y}, "flags": 0, "scale_val": 256}


class StaticPlateTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        make_room(self.root, 1, [(30, 12)])                      # a chair: one frame
        make_room(self.root, 2, [(10, 24), (10, 24), (11, 24)])  # a walker: three frames
        make_room(self.root, 3, [(7, 5)])                        # a sign: one frame
        self.metadata = {"objects": [obj(0, "CHAIR", 1, 5, 6), obj(1, "WALKER", 2, 40, 3),
                                     obj(2, "SIGN", 3, 2, 30)]}

    def tearDown(self):
        self.tmp.cleanup()

    def test_default_keeps_every_object(self):
        layers, skipped = plates.plan_layers(self.metadata, self.root)
        self.assertEqual(sorted(l.name for l in layers), ["CHAIR", "SIGN", "WALKER"])
        self.assertEqual(skipped, [])

    def test_static_only_drops_animated_objects(self):
        layers, skipped = plates.plan_layers(self.metadata, self.root, static_only=True)
        self.assertEqual(sorted(l.name for l in layers), ["CHAIR", "SIGN"])
        self.assertEqual([l.layer for l in layers], [1, 2])  # renumbered from 1 in draw order
        self.assertEqual(skipped, [{"object_index": 1, "name": "WALKER", "reason": "animated"}])
        chair = next(l for l in layers if l.name == "CHAIR")
        self.assertEqual((chair.x, chair.y, chair.width, chair.height), (5, 6, 30, 12))

    def test_setting_reads_config(self):
        cfg_path = self.root / "remaster.toml"
        cfg_path.write_text("[prepare]\nplate_layers = \"static\"\n")
        self.assertEqual(prepare.settings(load_config(cfg_path))["plate_layers"], "static")
        cfg_path.write_text("[prepare]\n")
        self.assertEqual(prepare.settings(load_config(cfg_path))["plate_layers"], "all")
        cfg_path.write_text("[prepare]\nplate_layers = \"some\"\n")
        with self.assertRaises(ValueError):
            prepare.settings(load_config(cfg_path))

    def test_prepare_passes_the_setting_through(self):
        source = Path(prepare.__file__).read_text()
        body = source.split("def prepare_scene")[1]
        self.assertIn("static_only=", body)
        self.assertIn('"plate_layers"', body)  # recorded in plate.json


if __name__ == "__main__":
    unittest.main()
