"""Acceptance test for delegate task `ambience2` (iteration 4): scaled objects and small-delta pixels.

Written by Opus; the implementation is delegated. Do not edit this file to make it pass.
Fixtures are non-square (room 60x40) so row/column mix-ups fail.

Iteration 3 rebuilt animated room objects on the redraw, but (1) skipped objects drawn scaled (scale_val != 256:
characters such as a doorman, whose frames carry the 1996 room behind them), and (2) kept old art for pixels
that differ only a little from the plate without being a pure brightness change (water shimmer), so pools stayed
1996 art. The engine draws a scaled frame of size (w, h) at position + (sDrawXOffset, sDrawYOffset) with size
(w * 256 // scale, h * 256 // scale) and resamples a 2w x 2h override to twice that box.
"""

import json
import sys
import tempfile
import unittest
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from remaster.config import load_config  # noqa: E402
from remaster.stages import assemble, extract, prepare  # noqa: E402

W, H = 60, 40


def plate_1x() -> np.ndarray:
    ys, xs = np.mgrid[0:H, 0:W]
    v = 60 + (xs * 2 + ys) % 100
    p = np.stack([v, v + 4, v - 4], axis=-1)
    p[20:26, 40:52] = (60, 120, 60)  # a flat green patch under the shimmer object
    return p.astype(np.uint8)


def redraw_2x() -> np.ndarray:
    ys, xs = np.mgrid[0:2 * H, 0:2 * W]
    return np.stack([40 + xs, 30 + ys * 2, 90 + (xs + ys) % 60], axis=-1).astype(np.uint8)


def obj(index, name, image_index, x, y, scale=256):
    return {"index": index, "name": name, "sprite_type": "active_bg_shape", "image_index": image_index,
            "position": {"x": x, "y": y}, "flags": 0, "scale_val": scale, "required_flags": []}


class Ambience2Test(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        (root / "remaster.toml").write_text("[golden]\nscenes = [4]\n")
        self.cfg = load_config(root / "remaster.toml")
        self.plate = plate_1x()
        prep = prepare.out_root(self.cfg) / "scene_012"
        prep.mkdir(parents=True)
        Image.fromarray(self.plate).save(prep / "plate.png")
        self.sprites = extract.scene_dir(self.cfg, "room-sprites", 12)
        rooms = extract.scene_dir(self.cfg, "rooms", 12)
        rooms.mkdir(parents=True)
        p = self.plate.astype(int)

        # SCALED (room_001), scale 128: frames 5x4 drawn as 10x8 at (8, 20); the frame samples the plate at every
        # second pixel (nearest), so it copies the background. Frame 1: offset (2, 1) -> drawn at (8+4, 20+2).
        def sampled(x0, y0, sw, sh, w, h):
            ys = y0 + np.arange(sh) * h // sh
            xs = x0 + np.arange(sw) * w // sw
            return p[np.ix_(ys, xs)].copy()
        f0 = sampled(8, 20, 5, 4, 10, 8)
        f0[2:4, 3:5] = (255, 0, 255)  # a 2x2 figure: keeps the old art
        f1 = sampled(12, 22, 5, 4, 10, 8)
        self.write_room(1, [(f0, 0, 0), (f1, 2, 1)])
        # SHIMMER (room_002) at (40, 20), 12x6: frame 0 left half = green patch + (24, 0, -24) (a small change
        # that is not a brightness change), right half magenta (big change, old art); frame 1 copies the plate.
        s0 = p[20:26, 40:52].copy()
        s0[:, :6] = s0[:, :6] + (24, 0, -24)
        s0[:, 6:] = (255, 0, 255)
        self.write_room(2, [(s0, 0, 0), (p[20:26, 40:52].copy(), 0, 0)])
        # WEAK (room_003) at (2, 2), 6x4: every frame is plate + (24, 0, -24) on a gradient patch whose hue it
        # changes: only small-delta pixels, no background copies. Small deltas must not make an object eligible.
        w0 = p[2:6, 2:8].copy()
        w0[..., 0] += 24
        w0[..., 2] -= 24
        w0[..., 1] = w0[..., 1] - 20  # break the brightness-ratio match
        self.write_room(3, [(np.clip(w0, 0, 255), 0, 0)] * 2)
        objects = [obj(0, "DOORMAN", 1, 8, 20, scale=128), obj(1, "POOL", 2, 40, 20), obj(2, "WEAK", 3, 2, 2)]
        (rooms / "metadata.json").write_text(json.dumps({"objects": objects}))
        self.redraw = redraw_2x()
        self.out = root / "out"

    def write_room(self, image_index, frames):
        room = self.sprites / f"room_{image_index:03d}"
        room.mkdir(parents=True)
        meta = []
        for i, (rgb, ox, oy) in enumerate(frames):
            rgb = np.asarray(np.clip(rgb, 0, 255), np.uint8)
            rgba = np.dstack([rgb, np.full(rgb.shape[:2], 255, np.uint8)])
            Image.fromarray(rgba, "RGBA").save(room / f"frame_{i:03d}.png")
            meta.append({"index": i, "file": f"frame_{i:03d}.png", "width": rgba.shape[1], "height": rgba.shape[0],
                         "offset_x": ox, "offset_y": oy, "invalid_placeholder": False})
        (room / "metadata.json").write_text(json.dumps({"room_index": image_index, "frame_count": len(frames),
                                                        "frames": meta}))

    def tearDown(self):
        self.tmp.cleanup()

    def run_it(self):
        return assemble.ambience_sprites(self.cfg, 12, Image.fromarray(self.redraw), self.out)

    def frame(self, image_index, i):
        return np.asarray(Image.open(self.out / f"room_{image_index:03d}" / f"frame_{i:03d}@2x.png")).astype(int)

    def test_which_objects_are_written(self):
        written = {w["name"]: w for w in self.run_it()}
        self.assertEqual(sorted(written), ["DOORMAN", "POOL"])
        self.assertEqual(written["DOORMAN"]["scale"], 128)
        self.assertFalse((self.out / "room_003").exists())

    def test_scaled_frame_takes_the_redraw_at_its_drawn_box(self):
        self.run_it()
        f0 = self.frame(1, 0)
        self.assertEqual(f0.shape, (8, 10, 4))  # twice the frame (5x4), not twice the drawn box (10x8)
        want = np.asarray(Image.fromarray(self.redraw[40:56, 16:36]).resize((10, 8), Image.LANCZOS)).astype(int)
        self.assertTrue(np.all(np.abs(f0[:4, :, :3] - want[:4]) <= 2))         # rows above the figure
        figure = f0[5:7, 7:9, :3]                                              # inside its 4x4 block
        self.assertTrue(figure[..., 0].mean() > 200 and figure[..., 1].mean() < 80)
        f1 = self.frame(1, 1)  # offset (2, 1) at scale 128 -> drawn at (8 + 4, 20 + 2)
        want1 = np.asarray(Image.fromarray(self.redraw[44:60, 24:44]).resize((10, 8), Image.LANCZOS)).astype(int)
        self.assertTrue(np.all(np.abs(f1[..., :3] - want1) <= 2))

    def test_small_deltas_ride_on_the_redraw(self):
        self.run_it()
        f0 = self.frame(2, 0)
        self.assertEqual(f0.shape, (12, 24, 4))
        base = self.redraw[40:52, 80:104].astype(int)
        want = np.clip(base[:, :12] + (24, 0, -24), 0, 255)
        np.testing.assert_array_equal(f0[:, :12, :3], want)            # redraw + the frame's delta
        blades = f0[1:11, 14:24, :3]                                    # big change: old art
        self.assertTrue(np.all(blades[..., 0] >= 240) and np.all(blades[..., 1] <= 15))
        np.testing.assert_array_equal(self.frame(2, 1)[..., :3], base)  # plain copy: the redraw

    def test_scaled_box_outside_the_plate_is_skipped(self):
        meta = json.loads((extract.scene_dir(self.cfg, "rooms", 12) / "metadata.json").read_text())
        meta["objects"][0]["position"] = {"x": 52, "y": 20}  # drawn 10 wide from x=52: leaves the 60-wide plate
        (extract.scene_dir(self.cfg, "rooms", 12) / "metadata.json").write_text(json.dumps(meta))
        self.assertEqual(sorted(w["name"] for w in self.run_it()), ["POOL"])

    def test_scaled_offsets_follow_the_engine(self):
        self.assertEqual(assemble.scaled_offset(5, 256), 5)
        self.assertEqual(assemble.scaled_offset(2, 128), 4)
        self.assertEqual(assemble.scaled_offset(9, 300), (8 * 256 // 300) + 1)   # > 256: -1 then +1
        self.assertEqual(assemble.scaled_offset(7, 200), 7 * 256 // 200)


if __name__ == "__main__":
    unittest.main()
