"""Acceptance test for delegate task `roomsprites` (iteration 2): static room objects cut from the 2x background.

Written by Opus; the implementation is delegated. Do not edit this file to make it pass.
Fixtures are non-square (room 60x40, frames 12x7 etc.) so row/column mix-ups fail.

The engine draws each static room object (a single-frame room image) over the background. Without an
override it draws the 1996 art over the redrawn room. Cutting each object's replacement frame out of the
room's own 2x background, at the place it is drawn, makes it pixel-identical to what is under it.
"""

import json
import sys
import tempfile
import unittest
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from remaster.config import load_config  # noqa: E402
from remaster.stages import assemble, prepare  # noqa: E402

W, H = 60, 40


def background_2x() -> Image.Image:
    ys, xs = np.mgrid[0:2 * H, 0:2 * W]
    arr = np.stack([xs * 2, ys * 3, (xs + ys) % 256], axis=-1).astype(np.uint8)
    return Image.fromarray(arr)


def frame(root: Path, image_index: int, sizes: list[tuple[int, int]], hole: bool = True) -> list[str]:
    room = root / f"room_{image_index:03d}"
    room.mkdir(parents=True)
    files = []
    for i, (w, h) in enumerate(sizes):
        a = np.full((h, w), 255, np.uint8)
        if hole:
            a[0, 0] = 0  # one transparent pixel, top-left
        rgba = np.dstack([np.full((h, w, 3), 9, np.uint8), a])
        Image.fromarray(rgba, "RGBA").save(room / f"frame_{i:03d}.png")
        files.append(str(room / f"frame_{i:03d}.png"))
    (room / "metadata.json").write_text(json.dumps({"room_index": image_index, "frame_count": len(sizes),
                                                    "frames": [{"index": i, "width": w, "height": h}
                                                               for i, (w, h) in enumerate(sizes)]}))
    return files


def layer(n, name, image_index, x, y, w, h, source, flipped=False, scale=256):
    return {"layer": n, "object_index": n, "name": name, "image_index": image_index, "frame": 0, "x": x, "y": y,
            "width": w, "height": h, "z": "normal", "flipped": flipped, "scale_val": scale, "source": source}


class RoomSpritesTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        (root / "remaster.toml").write_text("[golden]\nscenes = [4]\n")
        self.cfg = load_config(root / "remaster.toml")
        sprites = root / "sprites" / "scene_012"
        chair = frame(sprites, 1, [(12, 7)])
        flip = frame(sprites, 2, [(9, 5)])
        walker = frame(sprites, 3, [(6, 10), (6, 10)])
        shared = frame(sprites, 4, [(4, 4)])
        scaled = frame(sprites, 5, [(10, 8)])
        layers = [
            layer(1, "CHAIR", 1, 5, 6, 12, 7, chair[0]),
            layer(2, "FLIP", 2, 30, 2, 9, 5, flip[0], flipped=True),
            layer(3, "WALKER", 3, 40, 20, 6, 10, walker[0]),        # animated: never cut
            layer(4, "BUSTL", 4, 2, 30, 4, 4, shared[0]),           # one image used twice: ambiguous, skip
            layer(5, "BUSTR", 4, 50, 30, 4, 4, shared[0]),
            layer(6, "BIG", 5, 20, 20, 20, 16, scaled[0], scale=128),  # drawn at 2x its frame size
        ]
        prep = prepare.out_root(self.cfg) / "scene_012"
        prep.mkdir(parents=True)
        (prep / "plate.json").write_text(json.dumps({"layers": layers, "skipped": []}))
        self.out = root / "out"
        self.bg = background_2x()

    def tearDown(self):
        self.tmp.cleanup()

    def test_writes_one_override_per_unambiguous_static_object(self):
        written = assemble.room_sprites(self.cfg, 12, self.bg, self.out)
        names = sorted(w["name"] for w in written)
        self.assertEqual(names, ["BIG", "CHAIR", "FLIP"])
        for item in written:
            self.assertIn("path", item)
            self.assertTrue(Path(item["path"]).is_file())
        self.assertTrue((self.out / "room_001" / "frame_000@2x.png").is_file())
        self.assertFalse((self.out / "room_003").exists())
        self.assertFalse((self.out / "room_004").exists())

    def test_cut_matches_the_background_under_the_object(self):
        assemble.room_sprites(self.cfg, 12, self.bg, self.out)
        bg = np.asarray(self.bg)
        chair = np.asarray(Image.open(self.out / "room_001" / "frame_000@2x.png"))
        self.assertEqual(chair.shape, (14, 24, 4))  # 2x the 12x7 frame, RGBA
        np.testing.assert_array_equal(chair[..., :3], bg[12:26, 10:34])
        self.assertEqual(chair[0, 0, 3], 0)        # the frame's transparent pixel stays transparent
        self.assertEqual(chair[5, 9, 3], 255)
        # a flipped object is stored un-flipped (the engine flips it when drawing)
        flip = np.asarray(Image.open(self.out / "room_002" / "frame_000@2x.png"))
        self.assertEqual(flip.shape, (10, 18, 4))
        np.testing.assert_array_equal(flip[..., :3], bg[4:14, 60:78][:, ::-1])
        self.assertEqual(flip[0, 0, 3], 0)

    def test_scaled_object_is_resized_to_its_frame(self):
        assemble.room_sprites(self.cfg, 12, self.bg, self.out)
        big = Image.open(self.out / "room_005" / "frame_000@2x.png")
        self.assertEqual(big.size, (20, 16))  # 2x the 10x8 frame, not the 40x32 on-screen box
        self.assertEqual(big.mode, "RGBA")

    def test_no_plate_json_means_no_overrides(self):
        self.assertEqual(assemble.room_sprites(self.cfg, 99, self.bg, self.out), [])


if __name__ == "__main__":
    unittest.main()
