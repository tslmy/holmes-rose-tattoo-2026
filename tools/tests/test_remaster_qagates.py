"""Acceptance test for delegate task `qagates` (iteration 4): a relative floor gate and a tolerant objects gate.

Written by Opus; the implementation is delegated. Do not edit this file to make it pass.
Fixtures are non-square (baseline 60x40, redraw 120x80) so row/column mix-ups fail.

Calibration (iteration 3): the VLM floor check ("is every cyan walk zone on ground?") fails the untouched 1996
original in 18 of 23 rooms, because the game's walk zones routinely overlap furniture. So a failed floor check
only counts when the same check passes on the original. The objects gate failed rooms where one vague label
("Pictures", "Strangers' Room") was not re-detected although >= 85% of objects were; one such miss is now
tolerated unless the VLM diff reports that object removed.
"""

import json
import sys
import tempfile
import unittest
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from remaster.config import load_config  # noqa: E402
from remaster.stages import baseline, qa  # noqa: E402


class Reply:
    def __init__(self, text):
        self.text, self.seconds = text, 0.5


class FakeClient:
    model = "vlm-test"

    def __init__(self, floor=True):
        self.floor, self.calls = floor, []

    def chat(self, system, prompt, images=(), max_tokens=0):
        img = np.asarray(Image.open(images[0]).convert("RGB"))
        self.calls.append({"prompt": prompt, "shape": img.shape, "pixel": img[2, 2].tolist()})
        return Reply(json.dumps({"floor": self.floor, "problems": [] if self.floor else ["tint on a table"]}))


class FloorGateTest(unittest.TestCase):
    def test_truth_table(self):
        ok, bad, err = {"floor": True}, {"floor": False, "problems": ["x"]}, None
        self.assertIs(qa.floor_gate(ok, None), True)
        self.assertIs(qa.floor_gate(ok, bad), True)
        self.assertIs(qa.floor_gate(bad, bad), True)    # the original fails too: the check says nothing
        self.assertIs(qa.floor_gate(bad, ok), False)    # only the redraw fails: a real problem
        self.assertIs(qa.floor_gate(bad, err), False)   # no reference: stay strict
        self.assertIsNone(qa.floor_gate(None, ok))      # no floor review at all


class OriginalFloorTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        (root / "remaster.toml").write_text("[golden]\nscenes = [4]\n")
        self.cfg = load_config(root / "remaster.toml")
        b = baseline.out_root(self.cfg) / "scene_012"
        b.mkdir(parents=True)
        Image.new("RGB", (60, 40), (200, 10, 10)).save(b / "plate_esrgan.png")
        self.polys = [[[10, 50], [110, 50], [110, 78], [10, 78]]]

    def tearDown(self):
        self.tmp.cleanup()

    def test_checks_the_baseline_at_redraw_size_once_per_scene(self):
        client = FakeClient(floor=False)
        first = qa.original_floor(self.cfg, 12, client, self.polys, (120, 80))
        self.assertEqual(first["floor"], False)
        self.assertEqual(len(client.calls), 1)
        call = client.calls[0]
        self.assertEqual(call["prompt"], qa.VLM_FLOOR)
        self.assertEqual(call["shape"], (80, 120, 3))              # baseline resized to the redraw size
        self.assertTrue(abs(call["pixel"][0] - 200) <= 6 and call["pixel"][2] <= 20)  # untinted corner
        again = qa.original_floor(self.cfg, 12, client, self.polys, (120, 80))
        self.assertEqual(again, first)
        self.assertEqual(len(client.calls), 1)                     # cached for the other candidates
        self.assertTrue((qa.out_root(self.cfg) / "scene_012" / "floor_original.json").is_file())

    def test_cache_is_keyed_by_zones_size_and_model(self):
        client = FakeClient(floor=True)
        qa.original_floor(self.cfg, 12, client, self.polys, (120, 80))
        qa.original_floor(self.cfg, 12, client, [[[0, 60], [50, 60], [50, 79]]], (120, 80))
        qa.original_floor(self.cfg, 12, client, self.polys, (96, 80))
        other = FakeClient(floor=True)
        other.model = "vlm-other"
        qa.original_floor(self.cfg, 12, other, self.polys, (120, 80))
        self.assertEqual((len(client.calls), len(other.calls)), (3, 1))

    def test_missing_baseline_returns_none(self):
        self.assertIsNone(qa.original_floor(self.cfg, 99, FakeClient(), self.polys, (120, 80)))


def objs(found, missing, weak=()):
    total = found + len(missing) + len(weak)
    return {"objects_ok": not missing, "found_ratio": round(found / total, 3) if total else None,
            "missing_confident": list(missing), "missing_weak": list(weak)}


class ObjectsGateTest(unittest.TestCase):
    def test_all_found(self):
        self.assertEqual(qa.objects_gate(objs(6, []), []), (True, None))

    def test_one_vague_miss_is_tolerated(self):
        self.assertEqual(qa.objects_gate(objs(6, ["Pictures"]), []), (True, "Pictures"))
        self.assertEqual(qa.objects_gate(objs(9, ["Street Lamp"]), ["a crate"]), (True, "Street Lamp"))

    def test_miss_reported_removed_by_the_vlm_fails(self):
        self.assertEqual(qa.objects_gate(objs(9, ["Street Lamp"]), ["the street lamp on the left"]),
                         (False, None))
        self.assertEqual(qa.objects_gate(objs(6, ["Turkey Carpet"]), ["Carpet"]), (False, None))

    def test_short_words_do_not_match(self):
        # "the", "of", "a" and other words under 4 letters never count as a match
        self.assertEqual(qa.objects_gate(objs(9, ["Box of Tea"]), ["the jar"]), (True, "Box of Tea"))

    def test_low_ratio_or_two_misses_fail(self):
        self.assertEqual(qa.objects_gate(objs(4, ["Door"]), []), (False, None))          # 0.8 < 0.85
        self.assertEqual(qa.objects_gate(objs(12, ["Door", "Lamp"]), []), (False, None))
        self.assertEqual(qa.objects_gate(objs(5, ["Door"]), [], min_ratio=0.8), (True, "Door"))

    def test_weak_misses_count_in_the_ratio(self):
        self.assertEqual(qa.objects_gate(objs(6, ["Door"], weak=["Vendor"]), []), (False, None))  # 6/8


class WiringTest(unittest.TestCase):
    def test_evaluate_and_review_use_the_new_gates(self):
        source = Path(qa.__file__).read_text()
        evaluate = source.split("def evaluate")[1]
        self.assertIn("floor_gate(", evaluate)
        self.assertIn("objects_gate(", evaluate)
        self.assertIn('"objects_tolerated"', evaluate)
        review = source.split("def vlm_review")[1].split("\ndef ")[0]
        self.assertIn("original_floor(", review)
        self.assertIn('"floor_original"', review)


